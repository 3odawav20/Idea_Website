import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const backend = readFileSync("src/app/backend/supabaseClient.ts", "utf8");
const auth = readFileSync("src/app/pages/Auth.tsx", "utf8");

test("browser auth does not silently connect to a stale autogenerated project", () => {
  assert.doesNotMatch(backend, /utils\/supabase\/info/);
  assert.doesNotMatch(backend, /wkyvpulectwuaqskmjkr/);
  assert.match(backend, /VITE_SUPABASE_URL/);
  assert.match(backend, /VITE_SUPABASE_ANON_KEY/);
  assert.match(backend, /isValidAuthEndpoint\(url\)/);
  assert.match(backend, /export const supabase: SupabaseClient \| null/);
});

test("failed network signup and password reset leave feedback instead of throwing", () => {
  assert.match(auth, /failed to fetch\|fetch failed/);
  assert.match(auth, /catch \(error\)/);
  assert.match(auth, /setMessage\(authFailure\(error\)\)/);
  assert.match(auth, /role="alert"/);
  assert.match(auth, /setBusy\(false\)/);
});

test("app never embeds a private service role key", () => {
  assert.doesNotMatch(backend, /service_role\s*=|sb_secret_[a-z0-9]/i);
});
