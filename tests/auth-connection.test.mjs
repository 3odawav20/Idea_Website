import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const backend = readFileSync("src/app/backend/supabaseClient.ts", "utf8");
const auth = readFileSync("src/app/pages/AccountEntry.tsx", "utf8");
const accountApi = readFileSync("src/app/backend/phpAccounts.ts", "utf8");
const rolePolicy = readFileSync("src/app/backend/authValidation.ts", "utf8");

test("browser auth cannot fall back to Supabase or an autogenerated project", () => {
  assert.doesNotMatch(backend, /utils\/supabase\/info|wkyvpulectwuaqskmjkr/);
  assert.doesNotMatch(backend, /VITE_SUPABASE_URL|VITE_SUPABASE_ANON_KEY|createClient\(/);
  assert.match(backend, /isSupabaseConfigured = false/);
  assert.match(backend, /export const supabase = getUnavailableSupabaseClient\(\)/);
  assert.match(backend, /throw new Error\(backendConfigurationError\)/);
});

test("PHP account failures are validated and shown in the active auth form", () => {
  assert.match(accountApi, /response\.status === 204/);
  assert.match(accountApi, /ACCOUNT_API_EMPTY_RESPONSE/);
  assert.match(accountApi, /credentials:"same-origin"/);
  assert.match(auth, /authenticatePhp\("register"/);
  assert.match(auth, /authenticatePhp\("login"/);
  assert.match(auth, /catch\(err\)\{setError\(err instanceof Error\?err\.message/);
  assert.match(auth, /finally\{setBusy\(false\);/);
  assert.match(auth, /role="alert"/);
});

test("only server-confirmed buyer, supplier, and admin roles are accepted", () => {
  assert.match(rolePolicy, /SafeRole = "buyer" \| "supplier" \| "admin"/);
  assert.match(auth, /const expectedRole=isAdmin\?"admin":isBusiness\?"supplier":"buyer"/);
  assert.doesNotMatch(rolePolicy, /"designer"|"contractor"/);
});

test("app never embeds a private service role key", () => {
  assert.doesNotMatch(backend, /service_role\s*=|sb_secret_[a-z0-9]/i);
});
